def update_s3user(module, blade):
    """Update Object Store User"""
    changed = False
    api_version = get_rest_api_version(blade)
    exists = False
    s3user_facts = {}
    user = module.params["account"] + "/" + module.params["name"]
    if module.params["access_key"] or module.params["imported_key"]:
        key_count = 0
        if module.params["imported_key"] and not module.params["access_key"]:
            # Look the imported access key ID up directly before importing it:
            # re-importing an ID that already exists is an error on the array
            # and must be a no-op here when it already belongs to this user.
            # main() has placed the name in the realm of the account, so a
            # key of the same ID in another scope is not mistaken for it.
            existing_key = _get_key(
                module, blade, api_version, module.params["imported_key"]
            )
            if existing_key is not None:
                exists = True
                if not _same_name(_owner(existing_key), user):
                    module.warn("Imported key provided already belongs to another user")
        for key in _list_keys(module, blade, api_version):
            if _same_name(_owner(key), user):
                key_count += 1
        if not exists:
            if key_count < 2:
                if module.params["access_key"] and module.params["imported_key"]:
                    module.warn("'access_key: true' overrides imported keys")
                if module.params["access_key"]:
                    if key_count == 0 or (
                        key_count >= 1 and module.params["multiple_keys"]
                    ):
                        changed = True
                        if not module.check_mode:
                            if (
                                LooseVersion(CONTEXT_API_VERSION)
                                <= LooseVersion(api_version)
                                and module.params["context"]
                            ):
                                res = blade.post_object_store_access_keys(
                                    object_store_access_key=ObjectStoreAccessKeyPost(
                                        user={"name": user}
                                    ),
                                    context_names=[module.params["context"]],
                                )
                            else:
                                res = blade.post_object_store_access_keys(
                                    object_store_access_key=ObjectStoreAccessKeyPost(
                                        user={"name": user}
                                    )
                                )
                            if res.status_code == 200:
                                result = list(res.items)[0]
                                if not module.params["enable_key"]:
                                    if (
                                        LooseVersion(CONTEXT_API_VERSION)
                                        <= LooseVersion(api_version)
                                        and module.params["context"]
                                    ):
                                        blade.patch_object_store_access_keys(
                                            names=[result.name],
                                            object_store_access_key=ObjectStoreAccessKey(
                                                enabled=False
                                            ),
                                            context_names=[module.params["context"]],
                                        )
                                    else:
                                        blade.patch_object_store_access_keys(
                                            names=[result.name],
                                            object_store_access_key=ObjectStoreAccessKey(
                                                enabled=False
                                            ),
                                        )
                                s3user_facts["fb_s3user"] = _key_facts(
                                    module, user, result
                                )
                            else:
                                module.fail_json(
                                    msg="Object Store User {0} access Key import failed. "
                                    "Error: {1}".format(
                                        user,
                                        get_error_message(res),
                                    )
                                )
                else:
                    changed = True
                    if not module.check_mode:
                        if (
                            LooseVersion(CONTEXT_API_VERSION)
                            <= LooseVersion(api_version)
                            and module.params["context"]
                        ):
                            res = blade.post_object_store_access_keys(
                                names=[module.params["imported_key"]],
                                object_store_access_key=ObjectStoreAccessKeyPost(
                                    user={"name": user},
                                    secret_access_key=module.params["imported_secret"],
                                ),
                                context_names=[module.params["context"]],
                            )
                        else:
                            res = blade.post_object_store_access_keys(
                                names=[module.params["imported_key"]],
                                object_store_access_key=ObjectStoreAccessKeyPost(
                                    user={"name": user},
                                    secret_access_key=module.params["imported_secret"],
                                ),
                            )
                        if res.status_code == 200:
                            result = list(res.items)[0]
                            if not module.params["enable_key"]:
                                if (
                                    LooseVersion(CONTEXT_API_VERSION)
                                    <= LooseVersion(api_version)
                                    and module.params["context"]
                                ):
                                    blade.patch_object_store_access_keys(
                                        names=[result.name],
                                        object_store_access_key=ObjectStoreAccessKey(
                                            enabled=False
                                        ),
                                        context_names=[module.params["context"]],
                                    )
                                else:
                                    blade.patch_object_store_access_keys(
                                        names=[result.name],
                                        object_store_access_key=ObjectStoreAccessKey(
                                            enabled=False
                                        ),
                                    )
                        else:
                            module.fail_json(
                                msg="Object Store User {0} access Key creation failed. "
                                "Error: {1}".format(
                                    user,
                                    get_error_message(res),
                                )
                            )
            else:
                module.warn(
                    "Object Store User {0}: Maximum Access Key count reached".format(
                        user
                    )
                )
    module.exit_json(changed=changed, s3user_info=s3user_facts)


def create_s3user(module, blade):
    """Create Object Store Account"""
    s3user_facts = {}
    changed = True
    api_version = get_rest_api_version(blade)
    user = _user_name(module)
    if module.params["imported_key"] and not module.params["access_key"]:
        # A new user cannot own an access key that already exists, and the
        # array refuses to import an access key ID a second time. Settled
        # before the user is created, so check mode and a real run agree.
        existing_key = _get_key(
            module, blade, api_version, module.params["imported_key"]
        )
        if existing_key is not None:
            module.fail_json(
                msg="Access key {0} already belongs to object store user {1}. "
                "It cannot be imported for {2}.".format(
                    module.params["imported_key"], _owner(existing_key), user
                )
            )
    if not module.check_mode:
        if (
            LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
            and module.params["context"]
        ):
            res = blade.post_object_store_users(
                names=[user], context_names=[module.params["context"]]
            )
        else:
            res = blade.post_object_store_users(names=[user])
        if res.status_code != 200:
            module.fail_json(
                msg="Failed to create account {0}. Error:{1}".format(
                    user, get_error_message(res)
                )
            )
        if module.params["access_key"] and module.params["imported_key"]:
            module.warn("'access_key: true' overrides imported keys")
        if module.params["access_key"]:
            if (
                LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                and module.params["context"]
            ):
                res = blade.post_object_store_access_keys(
                    object_store_access_key=ObjectStoreAccessKeyPost(
                        user={"name": user}
                    ),
                    context_names=[module.params["context"]],
                )
            else:
                res = blade.post_object_store_access_keys(
                    object_store_access_key=ObjectStoreAccessKeyPost(
                        user={"name": user}
                    )
                )
            if res.status_code == 200:
                result = list(res.items)[0]
                if not module.params["enable_key"]:
                    if (
                        LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                        and module.params["context"]
                    ):
                        blade.patch_object_store_access_keys(
                            names=[result.name],
                            object_store_access_key=ObjectStoreAccessKey(enabled=False),
                            context_names=[module.params["context"]],
                        )
                    else:
                        blade.patch_object_store_access_keys(
                            names=[result.name],
                            object_store_access_key=ObjectStoreAccessKey(enabled=False),
                        )
                s3user_facts["fb_s3user"] = _key_facts(module, user, result)
            else:
                delete_s3user(module, blade, True)
                module.fail_json(
                    msg="Object Store User {0} creation failed. Error: {1}".format(
                        user, get_error_message(res)
                    )
                )
        else:
            if module.params["imported_key"]:
                if (
                    LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                    and module.params["context"]
                ):
                    res = blade.post_object_store_access_keys(
                        names=[module.params["imported_key"]],
                        object_store_access_key=ObjectStoreAccessKeyPost(
                            user={"name": user},
                            secret_access_key=module.params["imported_secret"],
                        ),
                        context_names=[module.params["context"]],
                    )
                else:
                    res = blade.post_object_store_access_keys(
                        names=[module.params["imported_key"]],
                        object_store_access_key=ObjectStoreAccessKeyPost(
                            user={"name": user},
                            secret_access_key=module.params["imported_secret"],
                        ),
                    )
                if res.status_code == 200:
                    result = list(res.items)[0]
                    if not module.params["enable_key"]:
                        if (
                            LooseVersion(CONTEXT_API_VERSION)
                            <= LooseVersion(api_version)
                            and module.params["context"]
                        ):
                            blade.patch_object_store_access_keys(
                                names=[result.name],
                                object_store_access_key=ObjectStoreAccessKey(
                                    enabled=False
                                ),
                                context_names=[module.params["context"]],
                            )
                        else:
                            blade.patch_object_store_access_keys(
                                names=[result.name],
                                object_store_access_key=ObjectStoreAccessKey(
                                    enabled=False
                                ),
                            )
                else:
                    # Roll the user back without exiting: delete_s3user would
                    # otherwise exit_json(changed=True) here and hide the
                    # array's error, so a rejected import looked like a
                    # successful create on every run.
                    delete_s3user(module, blade, True)
                    module.fail_json(
                        msg="Object Store User {0} creation failed with imported access key. "
                        "Error: {1}".format(user, get_error_message(res))
                    )
        if module.params["policy"]:
            # Build the list of valid policies rather than removing from the
            # list being iterated, which skips the element after each removal.
            policy_list = []
            for policy in module.params["policy"]:
                if (
                    LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                    and module.params["context"]
                ):
                    res = blade.get_object_store_access_policies(
                        names=[policy],
                        context_names=[module.params["context"]],
                    )
                else:
                    res = blade.get_object_store_access_policies(names=[policy])
                if res.status_code != 200:
                    module.warn("Policy {0} is not valid. Ignoring...".format(policy))
                else:
                    policy_list.append(policy)
            username = module.params["account"] + "/" + module.params["name"]
            for policy in policy_list:
                if (
                    LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                    and module.params["context"]
                ):
                    res = blade.get_object_store_users_object_store_access_policies(
                        member_names=[username],
                        policy_names=[policy],
                        context_names=[module.params["context"]],
                    )
                else:
                    res = blade.get_object_store_users_object_store_access_policies(
                        member_names=[username], policy_names=[policy]
                    )
                if not list(res.items):
                    if (
                        LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                        and module.params["context"]
                    ):
                        res = (
                            blade.post_object_store_access_policies_object_store_users(
                                member_names=[username],
                                policy_names=[policy],
                                context_names=[module.params["context"]],
                            )
                        )
                    else:
                        res = (
                            blade.post_object_store_access_policies_object_store_users(
                                member_names=[username],
                                policy_names=[policy],
                            )
                        )
                    if res.status_code != 200:
                        module.warn(
                            "Failed to add policy {0} to account user {1}. Error: {2}. Skipping...".format(
                                policy,
                                username,
                                get_error_message(res),
                            )
                        )
            if "pure:policy/full-access" not in policy_list:
                # Older Purity//FB releases added pure:policy/full-access to a
                # new user by default; current releases add nothing. When an
                # explicit list is given, drop the default only if it is there.
                if (
                    LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                    and module.params["context"]
                ):
                    res = blade.get_object_store_users_object_store_access_policies(
                        member_names=[username],
                        policy_names=["pure:policy/full-access"],
                        context_names=[module.params["context"]],
                    )
                else:
                    res = blade.get_object_store_users_object_store_access_policies(
                        member_names=[username],
                        policy_names=["pure:policy/full-access"],
                    )
                if res.status_code == 200 and list(res.items):
                    if (
                        LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
                        and module.params["context"]
                    ):
                        blade.delete_object_store_access_policies_object_store_users(
                            member_names=[username],
                            policy_names=["pure:policy/full-access"],
                            context_names=[module.params["context"]],
                        )
                    else:
                        blade.delete_object_store_access_policies_object_store_users(
                            member_names=[username],
                            policy_names=["pure:policy/full-access"],
                        )
    module.exit_json(changed=changed, s3user_info=s3user_facts)


def remove_key(module, blade):
    """Remove Access Key from User"""
    changed = False
    api_version = get_rest_api_version(blade)
    key = _get_own_key(module, blade, api_version)
    if key is not None:
        changed = True
        if not module.check_mode:
            res = blade.delete_object_store_access_keys(
                names=[key.name], **_context_kwargs(module, api_version)
            )
            if res.status_code != 200:
                module.fail_json(
                    msg="Failed to delete access key {0}. "
                    "Error: {1}".format(
                        module.params["key_name"], get_error_message(res)
                    )
                )
    module.exit_json(changed=changed)


def change_key(module, blade):
    """Change state of Access Key"""
    changed = False
    api_version = get_rest_api_version(blade)
    key = _get_own_key(module, blade, api_version)
    if key is None:
        module.fail_json(
            msg="Access key {0} does not exist. Object store user {1} has no "
            "such access key.".format(module.params["key_name"], _user_name(module))
        )
    if bool(key.enabled) != module.params["enable_key"]:
        changed = True
        if not module.check_mode:
            res = blade.patch_object_store_access_keys(
                names=[key.name],
                object_store_access_key=ObjectStoreAccessKey(
                    enabled=module.params["enable_key"]
                ),
                **_context_kwargs(module, api_version)
            )
            if res.status_code != 200:
                module.fail_json(
                    msg="Failed to change state of access key {0}. "
                    "Error: {1}".format(
                        module.params["key_name"], get_error_message(res)
                    )
                )
    module.exit_json(changed=changed)


def delete_s3user(module, blade, internal=False):
    """Delete Object Store Account"""
    changed = True
    api_version = get_rest_api_version(blade)
    if not module.check_mode:
        user = module.params["account"] + "/" + module.params["name"]
        if (
            LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
            and module.params["context"]
        ):
            res = blade.delete_object_store_users(
                names=[user], context_names=[module.params["context"]]
            )
        else:
            res = blade.delete_object_store_users(names=[user])
        if res.status_code != 200:
            module.fail_json(
                msg="Object Store Account {0}: Deletion failed".format(
                    module.params["name"]
                )
            )
    if internal:
        return
    module.exit_json(changed=changed)


def main():
    argument_spec = purefb_argument_spec()
    argument_spec.update(
        dict(
            name=dict(required=True, type="str"),
            account=dict(required=True, type="str"),
            # access_key and enable_key are switches, not credentials, but
            # validate-modules treats any option whose name ends in "key" as a
            # potential secret. They are marked safe explicitly, as their
            # neighbours already were.
            access_key=dict(default="false", type="bool", no_log=False),
            multiple_keys=dict(default="false", type="bool"),
            imported_key=dict(type="str", no_log=False),
            key_name=dict(type="str", no_log=False, aliases=["remove_key"]),
            enable_key=dict(type="bool", default=True, no_log=False),
            imported_secret=dict(type="str", no_log=True),
            policy=dict(type="list", elements="str"),
            state=dict(
                default="present",
                choices=["present", "absent", "remove_key", "keystate"],
            ),
            context=dict(type="str", default=""),
        )
    )

    required_together = [["imported_key", "imported_secret"]]
    required_if = [
        ["state", "remove_key", ["key_name"]],
        ["state", "keystate", ["key_name"]],
    ]

    module = AnsibleModule(
        argument_spec,
        required_together=required_together,
        required_if=required_if,
        supports_check_mode=True,
    )

    if not HAS_PYPURECLIENT:
        module.fail_json(msg="py-pure-client sdk is required for this module")

    state = module.params["state"]
    blade = get_system(module)
    api_version = get_rest_api_version(blade)
    if (
        LooseVersion(CONTEXT_API_VERSION) <= LooseVersion(api_version)
        and not module.params["context"]
    ):
        # If no context is provided set the context to the local array name
        fleet_res = blade.get_fleets()
        if fleet_res.status_code == 200 and list(fleet_res.items):
            module.params["context"] = list(blade.get_arrays().items)[0].name

    upper = False
    for element in module.params["account"]:
        if element.isupper():
            upper = True
            break
    if upper:
        module.warn("Changing account name to lowercase...")
        module.params["account"] = module.params["account"].lower()

    # An access key is addressed in the realm of the account the task names.
    if state in ("remove_key", "keystate"):
        _qualify_key(module, "key_name")
    elif (
        state == "present"
        and module.params["imported_key"]
        and not module.params["access_key"]
    ):
        _qualify_key(module, "imported_key")

    s3acc = get_s3acc(module, blade)
    if not s3acc:
        module.fail_json(
            msg="Object Store Account {0} does not exist".format(
                module.params["account"]
            )
        )

    s3user = get_s3user(module, blade)

    if state == "absent" and s3user:
        delete_s3user(module, blade)
    elif state == "present" and s3user:
        update_s3user(module, blade)
    elif not s3user and state == "present":
        create_s3user(module, blade)
    elif state == "remove_key" and s3user:
        remove_key(module, blade)
    elif state == "keystate":
        if not s3user:
            module.fail_json(
                msg="Object Store User {0} does not exist. The state of access "
                "key {1} cannot be set.".format(
                    _user_name(module), module.params["key_name"]
                )
            )
        change_key(module, blade)
    else:
        module.exit_json(changed=False)


if __name__ == "__main__":
    main()
